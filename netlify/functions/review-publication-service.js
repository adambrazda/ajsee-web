import {
  transitionReviewPublication,
  assertReviewPublicationInvariant
} from '../../scripts/review-publication-state.mjs';

function createServiceError(
  status,
  code
) {
  const error =
    new Error(code);

  error.status =
    status;

  error.code =
    code;

  return error;
}

function validateConfiguration({
  githubClient,
  repository,
  baseBranch
}) {
  if (
    !githubClient ||
    typeof githubClient !== 'object'
  ) {
    throw new Error(
      'githubClient is required'
    );
  }

  if (
    !repository ||
    typeof repository.owner !== 'string' ||
    !repository.owner.trim() ||
    typeof repository.repo !== 'string' ||
    !repository.repo.trim()
  ) {
    throw new Error(
      'Valid GitHub repository configuration is required'
    );
  }

  if (
    typeof baseBranch !== 'string' ||
    !baseBranch.trim()
  ) {
    throw new Error(
      'baseBranch is required'
    );
  }
}

function reviewPathForSlug(
  slug
) {
  return (
    `content/reviews/items/${slug}.json`
  );
}

function parseReviewFile({
  slug,
  source
}) {
  let review;

  try {
    review =
      JSON.parse(source);
  }
  catch {
    throw createServiceError(
      409,
      'review-json-invalid'
    );
  }

  if (
    !review ||
    typeof review !== 'object' ||
    Array.isArray(review) ||
    review.slug !== slug
  ) {
    throw createServiceError(
      409,
      'review-data-mismatch'
    );
  }

  try {
    assertReviewPublicationInvariant(
      review
    );
  }
  catch {
    throw createServiceError(
      409,
      'review-publication-state-invalid'
    );
  }

  return review;
}

function serializeReview(
  review,
  originalSource
) {
  const lineEnding =
    originalSource.includes('\r\n')
      ? '\r\n'
      : '\n';

  return (
    JSON.stringify(
      review,
      null,
      2
    )
      .replace(
        /\n/g,
        lineEnding
      ) +
    lineEnding
  );
}

function assertPublicationOnlyChange(
  before,
  after
) {
  const ignored =
    new Set([
      'status',
      'published',
      'publishedAt'
    ]);

  const beforeComparable = {};
  const afterComparable = {};

  for (
    const [
      key,
      value
    ] of Object.entries(before)
  ) {
    if (!ignored.has(key)) {
      beforeComparable[key] =
        value;
    }
  }

  for (
    const [
      key,
      value
    ] of Object.entries(after)
  ) {
    if (!ignored.has(key)) {
      afterComparable[key] =
        value;
    }
  }

  if (
    JSON.stringify(beforeComparable) !==
    JSON.stringify(afterComparable)
  ) {
    throw createServiceError(
      500,
      'publication-scope-violation'
    );
  }
}

function publicationBranchName(
  slug,
  baseSha
) {
  const shortSha =
    String(baseSha || '')
      .trim()
      .slice(0, 12);

  if (!shortSha) {
    throw createServiceError(
      502,
      'github-base-sha-missing'
    );
  }

  return (
    `admin/publish-${slug}-${shortSha}`
  );
}

function pullRequestTitle(
  review
) {
  const label =
    review.contentType === 'preview'
      ? 'preview'
      : 'review';

  return (
    `Publish ${review.showTitle || review.slug} ${label}`
  );
}

function pullRequestBody({
  review,
  user
}) {
  const requestedBy =
    String(
      user?.email ||
      user?.id ||
      'AJSEE admin'
    )
      .trim()
      .slice(0, 254);

  return [
    '## Summary',
    '',
    `Publishes the approved AJSEE ${review.contentType === 'preview' ? 'theatre preview' : 'review'}.`,
    '',
    '## Publication change',
    '',
    '- status: approved → published',
    '- published: false → true',
    '- publishedAt: generated by AJSEE publication workflow',
    '',
    '## Safety',
    '',
    '- publication state created by the shared AJSEE transition logic',
    '- publication-only content change',
    '- production release still requires pull request checks and merge',
    '',
    `Requested by: ${requestedBy}`
  ].join('\n');
}

async function readReviewFromMain({
  githubClient,
  repository,
  baseBranch,
  slug,
  ref = baseBranch
}) {
  const path =
    reviewPathForSlug(
      slug
    );

  const file =
    await githubClient.getFile({
      owner:
        repository.owner,

      repo:
        repository.repo,

      path,

      ref
    });

  if (
    !file ||
    typeof file.sha !== 'string' ||
    typeof file.content !== 'string'
  ) {
    throw createServiceError(
      502,
      'github-review-file-invalid'
    );
  }

  const review =
    parseReviewFile({
      slug,
      source:
        file.content
    });

  return {
    path,
    fileSha:
      file.sha,
    source:
      file.content,
    review
  };
}

export function createReviewPublicationService({
  githubClient,
  repository,
  baseBranch = 'main',
  nowFn =
    () =>
      new Date().toISOString()
} = {}) {
  validateConfiguration({
    githubClient,
    repository,
    baseBranch
  });

  async function getStatus({
    slug
  }) {
    const {
      review
    } =
      await readReviewFromMain({
        githubClient,
        repository,
        baseBranch,
        slug
      });

    const isPublished =
      review.status === 'published' &&
      review.published === true;

    const canPrepare =
      review.status === 'approved' &&
      review.published === false &&
      review.publishedAt === '';

    return {
      slug,
      state:
        isPublished
          ? 'published'
          : review.status,

      published:
        review.published,

      publishedAt:
        review.publishedAt || null,

      canPrepare,

      publication:
        null
    };
  }

  async function preparePublication({
    slug,
    user
  }) {
    const branchHead =
      await githubClient
        .getBranchHead({
          owner:
            repository.owner,

          repo:
            repository.repo,

          branch:
            baseBranch
        });

    if (
      !branchHead ||
      typeof branchHead.sha !== 'string' ||
      !branchHead.sha.trim()
    ) {
      throw createServiceError(
        502,
        'github-base-sha-missing'
      );
    }

    const {
      path,
      fileSha,
      source,
      review
    } =
      await readReviewFromMain({
        githubClient,
        repository,
        baseBranch,
        slug,
        ref:
          branchHead.sha
      });

    if (
      review.status === 'published' &&
      review.published === true
    ) {
      throw createServiceError(
        409,
        'review-already-published'
      );
    }

    if (
      review.status !== 'approved' ||
      review.published !== false ||
      review.publishedAt !== ''
    ) {
      throw createServiceError(
        409,
        'review-not-approved'
      );
    }

    const branch =
      publicationBranchName(
        slug,
        branchHead.sha
      );

    const existingPullRequest =
      await githubClient
        .findOpenPullRequest({
          owner:
            repository.owner,

          repo:
            repository.repo,

          base:
            baseBranch,

          head:
            branch
        });

    if (existingPullRequest) {
      return {
        slug,
        state:
          'preparing',

        branch,

        pullRequest:
          existingPullRequest,

        existing:
          true
      };
    }

    const existingPublicationPullRequest =
      await githubClient
        .findOpenPullRequestByHeadPrefix({
          owner:
            repository.owner,

          repo:
            repository.repo,

          base:
            baseBranch,

          headPrefix:
            `admin/publish-${slug}-`
        });

    if (existingPublicationPullRequest) {
      return {
        slug,
        state:
          'preparing',

        branch:
          existingPublicationPullRequest.head ||
          branch,

        pullRequest: {
          number:
            existingPublicationPullRequest.number,

          url:
            existingPublicationPullRequest.url
        },

        existing:
          true
      };
    }

    let nextReview;

    try {
      nextReview =
        transitionReviewPublication(
          review,
          'publish',
          nowFn()
        );
    }
    catch (error) {
      throw createServiceError(
        409,
        error?.message ||
          'publication-transition-failed'
      );
    }

    assertPublicationOnlyChange(
      review,
      nextReview
    );

    const nextSource =
      serializeReview(
        nextReview,
        source
      );

    await githubClient
      .createBranch({
        owner:
          repository.owner,

        repo:
          repository.repo,

        branch,

        sha:
          branchHead.sha
      });

    await githubClient
      .updateFile({
        owner:
          repository.owner,

        repo:
          repository.repo,

        path,

        branch,

        sha:
          fileSha,

        content:
          nextSource,

        message:
          `content: publish ${review.showTitle || slug}`
      });

    const pullRequest =
      await githubClient
        .createPullRequest({
          owner:
            repository.owner,

          repo:
            repository.repo,

          title:
            pullRequestTitle(
              review
            ),

          body:
            pullRequestBody({
              review,
              user
            }),

          base:
            baseBranch,

          head:
            branch
        });

    if (
      !pullRequest ||
      !Number.isInteger(
        pullRequest.number
      ) ||
      typeof pullRequest.url !== 'string'
    ) {
      throw createServiceError(
        502,
        'github-pull-request-invalid'
      );
    }

    return {
      slug,
      state:
        'preparing',

      branch,

      pullRequest,

      existing:
        false
    };
  }

  return {
    getStatus,
    preparePublication
  };
}
